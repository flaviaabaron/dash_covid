import pandas as pd
import plotly.express as px
import streamlit as st

# confi a pag para aparecer no topo a palavra e usar toda a tela
st.set_page_config(page_title='Dashcovid', layout='wide')

#dar um titulo
st.title('DASHCOVID: Um dashboad sobre dados Covid')

#acessar dados
df = pd.read_csv('WHO_time_series.csv')

from plotly.graph_objs import XAxis
#construir os graficos desejados
fig1 = px.line(df, x='Date_reported', y='Cumulative_cases', color='Country',title='Dados de Covid no Mundo')
fig1.update_layout(xaxis_title = 'Data', yaxis_title= 'Cumulativo', title_font_size = 30)
fig1.show()

